export const MAX_EMPLOYEE_ID_LENGTH = 64
const EMPLOYEE_ID_CHARACTER = String.raw`[A-Za-z0-9_\-]`
export const NEW_EMPLOYEE_ID_PATTERN = `[A-Za-z0-9]${EMPLOYEE_ID_CHARACTER}{0,${MAX_EMPLOYEE_ID_LENGTH - 1}}`
export const EMPLOYEE_PREFIX_PATTERN = `${EMPLOYEE_ID_CHARACTER}{0,${MAX_EMPLOYEE_ID_LENGTH}}`

export const NEW_EMPLOYEE_ID = new RegExp(`^${NEW_EMPLOYEE_ID_PATTERN}$`)
export const EMPLOYEE_PREFIX = new RegExp(`^${EMPLOYEE_PREFIX_PATTERN}$`)
export const EMPLOYEE_ID = new RegExp(`^${EMPLOYEE_ID_CHARACTER}{1,${MAX_EMPLOYEE_ID_LENGTH}}$`)
